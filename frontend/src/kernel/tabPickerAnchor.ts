/**
 * 162：**标签收纳浮窗贴着「+N」那颗按钮开**，不再钉在标签栏左端。
 *
 * 要求（原话）：「窗口过多收纳展开放在展开按钮那里，而不是放在左边」。
 *
 * 140 那版把浮窗写死成 `position: fixed; top: 36px; left: 18px` —— 那是照着
 * 「首个标签的左边界 = 收起后窄边的右边界」这条对齐线放的。可那颗「+N」长在标签串
 * 的尾巴上（右边还跟着「+」和「打开文件」两颗），于是**按钮在右、浮窗在左**，
 * 中间隔着整栏标签：点完按钮眼睛要横穿一整栏才找得到列表，收起的那几颗也看不出在哪儿。
 *
 * 这一份只算数、不碰 DOM：把按钮那一帧的矩形和视口尺寸换算成浮窗的锚点，
 * 好处是判据能钉在纯函数上（单位层），也能钉在真元素上（E2E / 桌面），
 * 而这两层必须给出同一个答案。
 *
 * 三条口径：
 * 1. **右缘与按钮右缘齐平**（不是左缘对齐按钮左缘）。那颗按钮最窄 26px，而浮窗至少
 *    240px；左缘对齐的话窗口一窄就整片捅出左边界，右缘齐平天然被窗口右缘挡住。
 * 2. **永远不贴窗边、永远不出界**：右缘至少留 `窗边距`，窄到放不下浮窗时改夹左缘 ——
 *    这条是"跟着按钮走"以后新出现的风险（原来钉左边不会有）。
 * 3. **按钮这一帧不在 → 返回 null**，调用方保持上一次的位置。
 *    「+N」是 `v-if` 的（收纳消失时按钮就没了），要是这里兜底返回 (0,0) 或左上默认值，
 *    浮窗会在人眼前跳一次 —— 与 146 那条「当前项记身份、不记位置」是同一类纪律。
 */

/** 只取这四个数：`DOMRect` 结构上就满足，测试里也不用造对象 */
export interface 矩形 {
  top: number;
  bottom: number;
  left: number;
  right: number;
}

/** 浮窗与按钮之间留的缝（px）：贴在按钮下沿，但隔 4px 不压着它 */
export const 浮窗间距 = 4;
/** 浮窗离窗口边缘的最小距离（px），也是"贴窗边"的下限 */
export const 窗边距 = 8;
/**
 * 夹左缘时用来估的浮窗宽度。
 * 取的是**偏大的那一头**：`.tabpicker` 写着 `min-width: 240px`，而实测拿到的是 `.menu` 的 188
 * （同一条 scoped 规则里 `.menu` 在后、把前面的 240 顶掉了 —— 这是 140 留下的一处 CSS 打架，
 * 记在 162 工单的「顺带发现」里，本轮按要求只动锚点、没顺手改宽度）。
 * 估大只会让夹得更早（浮窗往左多让一点），不会让它捅出窗口，所以留 240 而不是 188。
 */
export const 浮窗默认宽 = 240;
/** 窗口矮到装不下整片浮窗时，至少要让出这么多高度，浮窗才不会被顶到按钮上方去 */
export const 最小露出 = 120;

/** CSS `fixed` 用的锚点：`right` 而不是 `left` —— 见上面口径 1 */
export interface 锚点 {
  top: number;
  right: number;
}

/**
 * 算浮窗该钉在哪。
 *
 * @param 按钮 「+N」那颗按钮的矩形；`null` = 这一帧没有按钮，别动位置
 * @param 视口 `{ width, height }`，取 `window.innerWidth/innerHeight`
 * @param 浮窗宽 拿实测宽度时传进来；不传按 `min-width` 的 240 估（浮窗右缘齐平按钮，
 *              宽度只影响"左缘会不会捅出窗口"这一件事）
 */
export function 收纳浮窗锚点(
  按钮: 矩形 | null,
  视口: { width: number; height: number },
  浮窗宽: number = 浮窗默认宽
): 锚点 | null {
  if (!按钮) return null;
  if (!(视口.width > 0) || !(视口.height > 0)) return null;

  // 竖向：落在按钮下方；窗口矮到快放不下时往上夹，但绝不越过窗边距
  const 下沿 = 视口.height - 最小露出;
  let top = 按钮.bottom + 浮窗间距;
  if (top > 下沿) top = Math.max(浮窗间距, 下沿);

  // 横向：先按"右缘齐平按钮右缘"，再两头夹 —— 右不贴窗边，左不出窗口
  let right = 视口.width - 按钮.right;
  if (right < 窗边距) right = 窗边距;
  const 最大右 = 视口.width - 浮窗宽 - 窗边距;
  if (最大右 >= 窗边距 && right > 最大右) right = 最大右;

  return { top: Math.round(top), right: Math.round(right) };
}
