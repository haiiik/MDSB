import { expect, it } from "vitest";
import { 下一档, 写倍率, 读倍率, 缩放档, 缩放键 } from "../../src/kernel/mermaidZoom";

/**
 * 161（要求：「阅读模式的 mermaid 加上缩放功能」）：
 * 这一版把 146-A 那张"每张图自己的倍率"表从 NodeView 里搬出来给两档共用，
 * 尺子（档位步进）与身份（键怎么算）都是**纯函数** —— 先在这里钉住，
 * 别等到 E2E 里"图没变大"时才猜是哪一层错了（本项目吃过"判据自己会坏且不报错"的亏）。
 */

it("档位表就是 146-A 那一份，两档共用（数字变了要一起改判据）", () => {
  expect(缩放档).toEqual([0.3, 0.5, 0.75, 1, 1.25, 1.5, 2, 3]);
});

it("下一档：每侧走一档，中间值取最近的一档", () => {
  expect(下一档(1, 1)).toBe(1.25);
  expect(下一档(1, -1)).toBe(0.75);
  // 当前值不在表里（比如从别处搬来的 1.1）也要落在表内的某一档上，不能算出个野值
  expect(下一档(1.1, 1)).toBe(1.25);
  expect(下一档(1.1, -1)).toBe(1);
});

it("下一档：到顶 / 到底返回原值 —— 调用方据此把那颗键 disable（「不可用的选项干脆不摆」）", () => {
  expect(下一档(3, 1)).toBe(3);
  expect(下一档(0.3, -1)).toBe(0.3);
});

it("键按「标签页 + 第几张图」算：不同篇不串、同篇不同图不串", () => {
  expect(缩放键("A", 0)).toBe("A#0");
  expect(缩放键("A", 1)).toBe("A#1");
  expect(缩放键("B", 0)).toBe("B#0");
  expect(缩放键("A", 0)).not.toBe(缩放键("B", 0));
});

it("位置定不下来（序号为负）给空键：宁可回 100%，也不猜这是哪一张图", () => {
  expect(缩放键("A", -1)).toBe("");
  // 空键不记账：写了也读不回来，永远是默认那档
  写倍率("", 2);
  expect(读倍率("")).toBe(1);
});

it("倍率只认档位表里的值：表里没这一档就当没调过", () => {
  const k = 缩放键("T-161", 7);
  写倍率(k, 1.5);
  expect(读倍率(k)).toBe(1.5);
  // 146 那版按源区间存、161 按序号存，**旧键读不到就回 100%**（不能拿上一张图的倍率顶着）
  expect(读倍率(缩放键("T-161", 8))).toBe(1);
  expect(读倍率("T-161#6")).toBe(1);
});

it("改这张图的源码不该动倍率；换到另一张图（序号+1）也不该跟着变", () => {
  /*
   * 这条钉的是**为什么键里不放源码文本**：159 的主流程是"把这张图放大，然后就地改一个字"，
   * 键里带文本的话改完就变成另一个键 → 图当场缩回 100%（146 按源区间存也有同一身毛病，
   * 区间的末端随字数挪）。序号在打字时不变，这是 161 换键的直接理由。
   */
  const k = 缩放键("T-161-文本", 0);
  写倍率(k, 2);
  expect(读倍率(缩放键("T-161-文本", 0))).toBe(2);
  写倍率(缩放键("T-161-文本", 1), 0.5);
  // 第二张图自己的一档，不许把第一张带着走
  expect(读倍率(k)).toBe(2);
  expect(读倍率(缩放键("T-161-文本", 1))).toBe(0.5);
});
