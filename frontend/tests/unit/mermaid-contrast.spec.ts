import { expect, it } from "vitest";
import { 对比度, 相对亮度 } from "../../src/kernel/mermaid";

/**
 * 152（要求：「浅色主题可以看清，深色主题看不清啊，我觉得是软件层面的问题」）：
 * 深色档里文档写了浅底的节点，字被主题翻成浅灰 → 浅底 + 浅字。
 * 兜底靠的就是这两个纯函数，先把"尺子"本身钉住 ——
 * 尺子错了，E2E 那五条"每个节点都 ≥4.5"会一起绿着骗人（本项目吃过"判据自己会坏且不报错"的亏）。
 */

it("对比度：截图那一组实测值能复现（浅粉底 + 主题浅灰 = 读不了）", () => {
  // 浏览器里量到的就是这两个数，判据的及格线 4.5 也据此定
  expect(对比度("rgb(255, 230, 230)", "rgb(204, 204, 204)")).toBeCloseTo(1.35, 1);
  expect(对比度("rgb(230, 240, 255)", "rgb(204, 204, 204)")).toBeCloseTo(1.4, 1);
  // 同档里"没写样式"的那个节点是配好的，不该被判定为需要修
  expect(对比度("rgb(31, 32, 32)", "rgb(204, 204, 204)")).toBeGreaterThan(4.5);
});

it("对比度：黑白两端是 21，同色是 1（WCAG 的定义域）", () => {
  expect(对比度("#ffffff", "#000000")).toBeCloseTo(21, 1);
  expect(对比度("#000000", "#ffffff")).toBeCloseTo(21, 1);
  expect(对比度("#7a1f1f", "#7a1f1f")).toBeCloseTo(1, 2);
});

it("相对亮度：白 > 灰 > 黑，且单调（翻字色时靠它决定配深字还是浅字）", () => {
  const 白 = 相对亮度([255, 255, 255]);
  const 中灰 = 相对亮度([128, 128, 128]);
  const 黑 = 相对亮度([0, 0, 0]);
  expect(白).toBeCloseTo(1, 2);
  expect(黑).toBe(0);
  expect(白).toBeGreaterThan(中灰);
  expect(中灰).toBeGreaterThan(黑);
});

it("解析不出来就当合格，绝不动手（宁可漏改也不误改作者的颜色）", () => {
  expect(对比度("none", "rgb(204, 204, 204)")).toBe(99);
  expect(对比度("rgb(255,230,230)", "")).toBe(99);
  // 全透明的底不是这个元素给的（渐变 / 父层画的），拿它算会翻错
  expect(对比度("rgba(255, 230, 230, 0)", "rgb(204, 204, 204)")).toBe(99);
});

it("三位十六进制与空格写法都要认（mermaid 与浏览器两种写法都会出现）", () => {
  expect(对比度("#fff", "#000")).toBeCloseTo(21, 1);
  expect(对比度("rgb(255, 255, 255)", "rgb(0 0 0)")).toBeCloseTo(21, 1);
});
